// Writes voice-clips/RECORDING-SCRIPT.md: every fixed sentence the voice menu
// (IVR) says, with the file name its recording should have. Run it again
// after changing the USSD or voice menu: sentences that changed get new names.
//
//   npm run voice:script
import fs from "node:fs";
import path from "node:path";
import { CLIPS_DIR, findClip, resetClipCache } from "../src/lib/voiceClips.js";
import { phraseCatalog } from "../src/services/voiceService.js";

const phrases = phraseCatalog();
resetClipCache();
const languages = fs.existsSync(CLIPS_DIR)
  ? fs.readdirSync(CLIPS_DIR, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()
  : [];

const done = (language) => phrases.filter((p) => findClip(p.text, language)).length;
const lines = [
  "# Voice menu recording script",
  "",
  "Record each sentence below as its own short audio file, and name the file exactly as shown.",
  "Put the files in `backend/voice-clips/<language>/`, for example `backend/voice-clips/en-lr/` for Liberian English",
  "or `backend/voice-clips/kpe/` for Kpelle. Say the meaning in that language; the file name stays the same.",
  "",
  "- Format: MP3 (or WAV), mono, one sentence per file, about half a second of quiet at the start and end.",
  "- Speak slowly and clearly, like explaining to an older farmer on a bad line.",
  "- Numbers in \"Press 1 for ...\" must match the key the farmer presses.",
  "- Sentences with names, prices and dates are not listed: the computer voice reads those.",
  "- Set `VOICE_CLIP_LANG` on Railway to the folder name to use (default `en-lr`).",
  "",
  "Generated by `npm run voice:script`. Run it again after changing the USSD or voice menu.",
  "",
  `${phrases.length} sentences.${languages.map((l) => ` ${l}: ${done(l)} recorded.`).join("")}`,
  "",
  `| # | File | Sentence${languages.map((l) => ` | ${l}`).join("")} |`,
  `| --- | --- | ---${languages.map(() => " | ---").join("")} |`,
  ...phrases.map(
    (p, i) =>
      `| ${i + 1} | \`${p.key}.mp3\` | ${p.text.replace(/\|/g, "\\|")}${languages.map((l) => ` | ${findClip(p.text, l) ? "yes" : ""}`).join("")} |`
  ),
  ""
];
fs.mkdirSync(CLIPS_DIR, { recursive: true });
const out = path.join(CLIPS_DIR, "RECORDING-SCRIPT.md");
fs.writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}: ${phrases.length} sentences.`);
for (const language of languages) console.log(`  ${language}: ${done(language)} of ${phrases.length} recorded`);
