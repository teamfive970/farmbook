// Writes voice-clips/RECORDING-SCRIPT.md: every voice menu prompt, which can
// be recorded, and what is translated and recorded in each language.
// Run it again after changing the prompts (voice-prompts/en.json).
//
//   npm run voice:script
import fs from "node:fs";
import path from "node:path";
import { CLIPS_DIR, findClip, resetClipCache } from "../src/lib/voiceClips.js";
import { VOICE_LANGUAGES, packStatus, promptKeys, promptText } from "../src/channels/prompts.js";

resetClipCache();
// Prompts only USSD uses (it shows text) are left out.
const USSD_ONLY = ["ussd.", "register.", "notify.", "summary.options", "prices.sourceShort", "activity.note"];
const keys = promptKeys().filter(({ key }) => !USSD_ONLY.some((prefix) => key.startsWith(prefix)));
const languages = VOICE_LANGUAGES.map(({ code }) => code);
const recordable = keys.filter((item) => !item.hasParams);

const lines = [
  "# Voice menu recording script",
  "",
  "Each prompt below is one audio file. Record it and save it as",
  "`backend/voice-clips/<language>/<prompt>.mp3` (or .wav), for example",
  "`backend/voice-clips/en/ivr.menu.title.mp3`.",
  "",
  "- **English** words are final. Record them as written, in clear Liberian English.",
  "- **Kpelle and Bassa**: first a native speaker translates each prompt into",
  "  `backend/voice-prompts/<language>.json` (same keys as `en.json`), a second native",
  "  speaker checks it, then it is recorded. Never use machine translation.",
  "- Format: MP3, mono, one prompt per file, about half a second of quiet at each end.",
  "- Speak slowly and clearly, like explaining to an older farmer on a bad line.",
  "- Prompts with a {name} or {number} in them can't be recorded: the computer voice",
  "  reads them (in English). They are listed at the end for translators only.",
  "",
  "Until a recording exists, the phone call uses the computer voice in English, and",
  "the browser simulator labels it \"English stand-in\".",
  "",
  `Generated by \`npm run voice:script\` on ${new Date().toISOString().slice(0, 10)}.`,
  "",
  "## Status",
  "",
  "| Language | Translated prompts | Recorded prompts |",
  "| --- | --- | --- |",
  ...languages.map((language) => {
    const status = packStatus(language);
    const recorded = recordable.filter(({ key }) => findClip(key, language)).length;
    const translated = language === "en" ? `${status.total} of ${status.total}` : `${status.translated} of ${status.total} (${status.status})`;
    return `| ${status.name} | ${translated} | ${recorded} of ${recordable.length} |`;
  }),
  "",
  "## Prompts to record",
  "",
  `| # | File | English words${languages.map((language) => ` | ${language}`).join("")} |`,
  `| --- | --- | ---${languages.map(() => " | ---").join("")} |`,
  ...recordable.map(({ key }, index) => {
    const marks = languages.map((language) => {
      if (findClip(key, language)) return "recorded";
      if (language !== "en" && promptText(key, {}, language).missing) return "needs translation";
      return "";
    });
    return `| ${index + 1} | \`${key}.mp3\` | ${promptText(key).text.replace(/\|/g, "\\|").replace(/\n/g, " / ")} | ${marks.join(" | ")} |`;
  }),
  "",
  "## Prompts read by the computer voice (translate only)",
  "",
  "| Key | English words |",
  "| --- | --- |",
  ...keys.filter((item) => item.hasParams).map(({ key, text }) => `| \`${key}\` | ${text.replace(/\|/g, "\\|")} |`),
  ""
];
fs.mkdirSync(CLIPS_DIR, { recursive: true });
const out = path.join(CLIPS_DIR, "RECORDING-SCRIPT.md");
fs.writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}: ${recordable.length} prompts to record.`);
for (const language of languages) {
  const status = packStatus(language);
  console.log(`  ${status.name}: ${status.translated} of ${status.total} translated, ${recordable.filter(({ key }) => findClip(key, language)).length} recorded`);
}
